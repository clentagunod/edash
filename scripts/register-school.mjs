import { applicationDefault, cert, getApps, initializeApp } from "firebase-admin/app";
import { FieldValue, getFirestore } from "firebase-admin/firestore";
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

function option(name, fallback = "") {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 ? String(process.argv[index + 1] || "").trim() : fallback;
}

function hasFlag(name) {
  return process.argv.includes(`--${name}`);
}

function usage() {
  console.log(`Usage:
  npm run registry:register-school -- --registry-project <central-project-id> --registration-file <json-file> [options]

Options:
  --service-account <path>  Admin service-account JSON path; otherwise ADC is used
  --deploy-rules            Deploy school-registry.rules before writing the registration
  --dry-run                 Validate and display the target document without writing
  --help                    Show this help

The registration JSON contains only public Firebase Web App configuration and
school metadata, including colorGradientTag and schoolHead contact details.
The schoolHead.updatedAt timestamp is generated by Firestore. Never put
service-account credentials in that file.
`);
}

export function validateRegistration(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error("Registration file must contain one JSON object.");
  }

  const id = String(value.id || "").trim();
  if (!/^[a-z0-9][a-z0-9-]{1,62}$/.test(id)) {
    throw new Error("id must be a stable lowercase ID containing 2-63 letters, digits, or hyphens.");
  }

  const name = String(value.name || "").trim();
  const nickname = String(value.nickname || "").trim();
  const tagline = value.tagline === undefined ? "" : value.tagline;
  if (value.projectName !== undefined && (typeof value.projectName !== "string" || value.projectName.length > 120)) {
    throw new Error("projectName must be a string of at most 120 characters.");
  }
  if (!name || name.length > 120) throw new Error("name is required and must be at most 120 characters.");
  if (!nickname || nickname.length > 64) throw new Error("nickname is required and must be at most 64 characters.");
  if (typeof tagline !== "string" || tagline.length > 240) {
    throw new Error("tagline must be a string of at most 240 characters.");
  }
  if (value.canUseEduAI !== undefined && typeof value.canUseEduAI !== "boolean") {
    throw new Error("canUseEduAI must be a boolean when supplied.");
  }
  const colorGradientTag = value.colorGradientTag;
  if (colorGradientTag !== undefined &&
    (typeof colorGradientTag !== "string" || !/^#[0-9a-fA-F]{6}$/.test(colorGradientTag))) {
    throw new Error("colorGradientTag must be a six-digit hexadecimal color such as #50A61E.");
  }
  if (typeof value.logoUrl !== "string" || !isSafeAssetReference(value.logoUrl)) {
    throw new Error("logoUrl must be a same-site path or an HTTPS URL.");
  }
  if (typeof value.videoUrl !== "string" || (value.videoUrl && !isSafeAssetReference(value.videoUrl))) {
    throw new Error("videoUrl must be empty or a same-site path/HTTPS direct video URL.");
  }

  const schoolInfo = value.schoolInfo;
  if (schoolInfo !== undefined) {
    if (!schoolInfo || typeof schoolInfo !== "object" || Array.isArray(schoolInfo)) {
      throw new Error("schoolInfo must be an object when supplied.");
    }
    for (const field of ["region", "divisionOffice", "district"]) {
      if (typeof schoolInfo[field] !== "string" || schoolInfo[field].length > 160) {
        throw new Error(`schoolInfo.${field} must be a string of at most 160 characters.`);
      }
    }
  }

  const schoolHead = value.schoolHead;
  if (schoolHead !== undefined) {
    if (!schoolHead || typeof schoolHead !== "object" || Array.isArray(schoolHead)) {
      throw new Error("schoolHead must be an object when supplied.");
    }
    for (const field of ["name", "position", "email", "phoneNumber"]) {
      if (typeof schoolHead[field] !== "string" || schoolHead[field].length > 160) {
        throw new Error(`schoolHead.${field} must be a string of at most 160 characters.`);
      }
    }
  }

  const config = value.firebaseConfig;
  const requiredConfigKeys = ["apiKey", "authDomain", "projectId", "storageBucket", "messagingSenderId", "appId"];
  if (!config || typeof config !== "object" || Array.isArray(config) ||
    requiredConfigKeys.some((key) => typeof config[key] !== "string" || !config[key].trim())) {
    throw new Error(`firebaseConfig must include non-empty strings for: ${requiredConfigKeys.join(", ")}.`);
  }

  const serviceFields = ["auditLogApiUrl", "feedbackApiUrl"];
  for (const field of serviceFields) {
    if (value[field] !== undefined &&
      (typeof value[field] !== "string" || (value[field] && !isHttpsUrl(value[field])))) {
      throw new Error(`${field} must be an empty string or an HTTPS URL.`);
    }
  }

  return {
    ...value,
    id,
    enabled: true,
    name,
    nickname,
    ...(value.projectName === undefined ? {} : { projectName: value.projectName.trim() }),
    ...(value.tagline === undefined ? {} : { tagline: tagline.trim() }),
    ...(value.colorGradientTag === undefined ? {} : { colorGradientTag }),
    logoUrl: value.logoUrl.trim(),
    videoUrl: value.videoUrl.trim(),
    ...(schoolInfo === undefined ? {} : { schoolInfo: {
      ...schoolInfo,
      ...Object.fromEntries(
        ["region", "divisionOffice", "district"].map((field) => [field, schoolInfo[field].trim()]),
      ),
    } }),
    ...(schoolHead === undefined ? {} : { schoolHead: {
      ...schoolHead,
      ...Object.fromEntries(
        ["name", "position", "email", "phoneNumber"].map((field) => [field, schoolHead[field].trim()]),
      ),
    } }),
    firebaseConfig: {
      ...config,
      ...Object.fromEntries(requiredConfigKeys.map((key) => [key, config[key].trim()])),
    },
    ...(value.auditLogApiUrl === undefined ? {} : { auditLogApiUrl: value.auditLogApiUrl.trim() }),
    ...(value.feedbackApiUrl === undefined ? {} : { feedbackApiUrl: value.feedbackApiUrl.trim() }),
  };
}

function mergeJsonFields(existing, updates) {
  const result = { ...existing };
  Object.entries(updates).forEach(([key, value]) => {
    const isPlainMap = value && typeof value === "object" && !Array.isArray(value) &&
      (Object.getPrototypeOf(value) === Object.prototype || Object.getPrototypeOf(value) === null);
    result[key] = isPlainMap
      ? mergeJsonFields(
          result[key] && typeof result[key] === "object" && !Array.isArray(result[key])
            ? result[key]
            : {},
          value,
        )
      : value;
  });
  return result;
}

export function buildSchoolDocument(registration, existingDocument, serverTimestamp) {
  const document = mergeJsonFields(existingDocument, registration);
  document.enabled = true;
  document.updatedAt = serverTimestamp;
  if (registration.schoolHead !== undefined) {
    document.schoolHead = mergeJsonFields(existingDocument.schoolHead || {}, registration.schoolHead);
    document.schoolHead.updatedAt = serverTimestamp;
  }
  return document;
}

function isSafeAssetReference(value) {
  try {
    const url = new URL(value, "https://edash.invalid");
    return url.protocol === "https:";
  } catch {
    return false;
  }
}

function isHttpsUrl(value) {
  try {
    return new URL(value).protocol === "https:";
  } catch {
    return false;
  }
}

function initializeRegistryAdmin(projectId) {
  const serviceAccountPath = option("service-account", process.env.GOOGLE_APPLICATION_CREDENTIALS);
  const appName = "edash-registry-provisioner";
  const existing = getApps().find((app) => app.name === appName);
  if (existing) return getFirestore(existing);

  const app = serviceAccountPath
    ? initializeApp({ credential: cert(resolve(serviceAccountPath)), projectId }, appName)
    : initializeApp({ credential: applicationDefault(), projectId }, appName);
  return getFirestore(app);
}

function deployRegistryRules(projectId) {
  const args = ["--yes", "firebase-tools", "deploy", "--only", "firestore:rules", "--project", projectId, "--config", "firebase.registry.json"];
  if (process.platform === "win32") {
    // Windows command shims (.cmd) must be invoked through cmd.exe; spawning
    // npx.cmd directly fails with EINVAL in Node's spawnSync implementation.
    execFileSync(process.env.ComSpec || "cmd.exe", ["/d", "/s", "/c", `npx.cmd ${args.join(" ")}`], { stdio: "inherit" });
    return;
  }
  execFileSync("npx", args, { stdio: "inherit" });
}

async function main() {
  if (hasFlag("help")) return usage();
  const registryProject = option("registry-project", process.env.EDASH_REGISTRY_PROJECT);
  const registrationFile = option("registration-file");
  if (!registryProject) throw new Error("Missing --registry-project (central E-Dash Firebase project ID).");
  if (!/^[a-z0-9][a-z0-9-]{4,28}[a-z0-9]$/.test(registryProject)) {
    throw new Error("--registry-project must be a valid lowercase Firebase project ID.");
  }
  if (!registrationFile) throw new Error("Missing --registration-file (path to the public school registration JSON).");

  const registration = validateRegistration(JSON.parse(await readFile(resolve(registrationFile), "utf8")));
  console.log(`Central project: ${registryProject}`);
  console.log(`Target document: schools/${registration.id}`);
  console.log(`School: ${registration.name}`);
  console.log(`Enabled: true`);
  if (hasFlag("dry-run")) {
    console.log(`Registration JSON fields: ${Object.keys(registration).filter((field) => field !== "id").join(", ")}`);
    console.log("Dry run complete; no Firestore writes or rule deployments made.");
    return;
  }

  if (hasFlag("deploy-rules")) {
    console.log("Deploying school-registry.rules...");
    deployRegistryRules(registryProject);
  }

  const db = initializeRegistryAdmin(registryProject);
  const { id, ...schoolDocument } = registration;
  const reference = db.collection("schools").doc(id);
  let updated = false;
  await db.runTransaction(async (transaction) => {
    const snapshot = await transaction.get(reference);
    updated = snapshot.exists;
    transaction.set(
      reference,
      buildSchoolDocument(schoolDocument, snapshot.data() || {}, FieldValue.serverTimestamp()),
    );
  });
  console.log(`${updated ? "Updated" : "Registered"} schools/${id} in the central E-Dash database.`);
  console.log("The school document was retained; supplied fields were updated and fields omitted from the JSON were preserved.");
  console.log("No Firebase Web App configuration values or credentials were printed.");
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main().catch((error) => {
    const message = String(error?.message || error);
    if (/default credentials|application default credentials/i.test(message)) {
      console.error(`School registration failed: Firebase Admin credentials are not configured.

Choose one:
  1. Run "gcloud auth application-default login" and sign in with an account that can write to the central registry project; or
  2. Store a registry-project service-account JSON outside the repository and rerun with:
     --service-account "C:\\secure\\firebase-admin\\edash-registry-admin.json"

Firebase CLI login ("firebase login") only authorizes rule deployment; it does not provide credentials for the Admin SDK Firestore write.
`);
      process.exitCode = 1;
      return;
    }
    console.error(`School registration failed: ${message}`);
    process.exitCode = 1;
  });
}
